"""Chat UI for the platform's agents.

Sign-in is OIDC against the platform's Cognito user pool (st.login). The user's
access token is sent to the agent runtime, whose JWT authorizer checks it; the
agent forwards it to the Gateway, so every tool call runs as this user.

Config comes from .streamlit/secrets.toml, generated by scripts/configure_frontend.sh.
"""

from __future__ import annotations

import json
import time
import uuid
from urllib.parse import quote

import requests
import streamlit as st

st.set_page_config(page_title="Agent Platform", page_icon="🤖", layout="wide")

CFG = st.secrets["platform"]
REGION: str = CFG["region"]
AGENTS: dict = {a["name"]: a for a in CFG["agents"]}
TOOL_LABELS = {"run_python": "Running Python", "x_amz_bedrock_agentcore_search": "Searching tools"}


# --------------------------------------------------------------------------- auth
if not st.user.get("is_logged_in"):
    st.title("Agent Platform")
    st.write("Sign in with your company account to chat with agents.")
    st.button("Sign in", type="primary", on_click=st.login)
    st.stop()

access_token: str = st.user.tokens["access"]


# --------------------------------------------------------------------------- state
def new_session_id() -> str:
    return f"{uuid.uuid4()}-{uuid.uuid4().hex[:8]}"  # AgentCore needs >= 33 chars


state = st.session_state
state.setdefault("chats", {})  # agent name -> {"session_id": str, "messages": [..]}


def chat_for(agent: str) -> dict:
    return state.chats.setdefault(agent, {"session_id": new_session_id(), "messages": []})


# --------------------------------------------------------------------------- sidebar
with st.sidebar:
    st.subheader(st.user.get("email") or st.user.get("name") or "Signed in")
    agent_name = st.radio(
        "Agent",
        list(AGENTS),
        format_func=lambda n: AGENTS[n]["display_name"],
        captions=[AGENTS[n]["description"] for n in AGENTS],
    )
    chat = chat_for(agent_name)
    if st.button("New chat", use_container_width=True):
        state.chats[agent_name] = {"session_id": new_session_id(), "messages": []}
        st.rerun()
    st.caption(f"Session `{chat['session_id'][:8]}…`")
    st.button("Sign out", on_click=st.logout, use_container_width=True)


# --------------------------------------------------------------------------- agent call
class AuthExpired(Exception):
    pass


def stream_agent(agent: dict, session_id: str, prompt: str, status):
    """Yield answer text from the agent's SSE stream; report tool use to `status`."""
    url = (
        f"https://bedrock-agentcore.{REGION}.amazonaws.com/runtimes/"
        f"{quote(agent['arn'], safe='')}/invocations?qualifier=DEFAULT"
    )
    headers = {
        "Authorization": f"Bearer {access_token}",
        "X-Amzn-Bedrock-AgentCore-Runtime-Session-Id": session_id,
        "Content-Type": "application/json",
        "Accept": "text/event-stream",
    }
    with requests.post(url, headers=headers, data=json.dumps({"prompt": prompt}), stream=True, timeout=900) as r:
        if r.status_code in (401, 403):
            raise AuthExpired(r.text[:300])
        r.raise_for_status()
        for raw in r.iter_lines(decode_unicode=True):
            if not raw or not raw.startswith("data: "):
                continue
            event = json.loads(raw[6:])
            kind = event.get("type") if isinstance(event, dict) else None
            if kind == "text":
                yield event["data"]
            elif kind == "tool_call":
                status.update(label=TOOL_LABELS.get(event["name"], f"Using {event['name']}"), state="running")
            elif kind == "tool_result":
                status.write(("✅ " if event.get("ok") else "⚠️ ") + event["name"])
            elif kind == "error":
                yield f"\n\n**Error:** {event['message']}"
            elif kind == "done":
                status.update(label="Done", state="complete")


def record_feedback(agent: str, session_id: str, index: int) -> None:
    value = state.get(f"fb-{session_id}-{index}")
    if value is None:
        return
    entry = {
        "ts": int(time.time()), "agent": agent, "session_id": session_id, "message_index": index,
        "rating": "up" if value == 1 else "down", "user": st.user.get("sub"),
    }
    # Shows up in the runtime's CloudWatch logs via the feedback log group, keyed by
    # session id, so it can be joined with traces and evaluations.
    try:
        import boto3

        logs = boto3.client("logs", region_name=REGION)
        logs.put_log_events(
            logGroupName=CFG["feedback_log_group"], logStreamName="ui",
            logEvents=[{"timestamp": entry["ts"] * 1000, "message": json.dumps(entry)}],
        )
    except Exception as e:  # feedback is best-effort; never break the chat
        st.toast(f"Feedback not saved: {e}")


# --------------------------------------------------------------------------- chat
agent = AGENTS[agent_name]
st.header(agent["display_name"])

for i, msg in enumerate(chat["messages"]):
    with st.chat_message(msg["role"]):
        st.markdown(msg["content"])
        if msg["role"] == "assistant":
            st.feedback("thumbs", key=f"fb-{chat['session_id']}-{i}",
                        on_change=record_feedback, args=(agent_name, chat["session_id"], i))

if prompt := st.chat_input(f"Message {agent['display_name']}"):
    chat["messages"].append({"role": "user", "content": prompt})
    with st.chat_message("user"):
        st.markdown(prompt)
    with st.chat_message("assistant"):
        status = st.status("Thinking…", expanded=False)
        try:
            answer = st.write_stream(stream_agent(agent, chat["session_id"], prompt, status))
        except AuthExpired:
            status.update(label="Session expired", state="error")
            st.warning("Your sign-in has expired or you don't have access to this agent. Sign in again.")
            st.button("Sign in again", on_click=st.logout)
            st.stop()
        except requests.RequestException as e:
            status.update(label="Failed", state="error")
            answer = f"**Could not reach the agent:** {e}"
            st.markdown(answer)
    chat["messages"].append({"role": "assistant", "content": answer if isinstance(answer, str) else str(answer)})
    st.rerun()
